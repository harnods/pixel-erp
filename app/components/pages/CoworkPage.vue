// ── Schedule ─────────────────────────────────────────────────────────────────
const scheduleOpen = ref(false)
const schedTaskTitle = ref('')
const schedCadence = ref<CoworkCadence>('Weekly')
const schedTime = ref('08:00')
const schedError = ref('')
function openSchedule() {
  schedTaskTitle.value = ''
  schedCadence.value = 'Weekly'
  schedTime.value = '08:00'
  schedError.value = ''
  scheduleOpen.value = true
}
function saveSchedule() {
  const cat = COWORK_CATALOG.find((c) => c.title === schedTaskTitle.value)
  if (!cat) { schedError.value = 'Select a task to schedule'; return }
  const nextRun = schedCadence.value === 'Daily' ? `Tomorrow · ${schedTime.value}`
    : schedCadence.value === 'Weekly' ? `Next Mon · ${schedTime.value}`
    : `1st of month · ${schedTime.value}`
  addSchedule({ title: cat.title, prompt: cat.prompt, module: cat.module, cadence: schedCadence.value, time: schedTime.value, nextRun, enabled: true })
  scheduleOpen.value = false
  toast.notify({ variant: 'success', title: 'Task scheduled' })
}

// ── Connections ──────────────────────────────────────────────────────────────
const google = useGoogleConnect()
const connecting = ref('')                          // id currently authorising
const connError = reactive<Record<string, string>>({})   // inline error per card
const connSample = reactive<Record<string, string>>({})  // live proof per card (e.g. email)

async function connectGoogle(c: CoworkConnection) {
  connError[c.id] = ''
  if (!google.isConfigured.value) {
    connError[c.id] = 'Google client ID not configured yet (NUXT_PUBLIC_GOOGLE_CLIENT_ID).'
    return
  }
  connecting.value = c.id
  try {
    const { sample } = await google.connect(c.scope!)
    setConnection(c.id, true)
    if (sample) connSample[c.id] = sample
    toast.notify({ variant: 'success', title: `${c.name} connected` })
  } catch (e: any) {
    connError[c.id] = e?.message === 'Google client ID not configured'
      ? 'Google client ID not configured yet.'
      : 'Could not connect. Please try again.'
  } finally {
    connecting.value = ''
  }
}
function disconnectConnection(c: CoworkConnection) {
  if (c.provider === 'google' && c.scope) google.disconnect(c.scope)
  delete connSample[c.id]
  setConnection(c.id, false)
  toast.notify({ variant: 'success', title: `${c.name} disconnected` })
}
function connectFake(c: CoworkConnection) {
  setConnection(c.id, true)
  toast.notify({ variant: 'success', title: `${c.name} connected` })
}
function addConnection() { toast.notify({ variant: 'info', title: 'Browse the connections marketplace — coming soon' }) }

