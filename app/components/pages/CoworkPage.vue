// `run` = execute immediately (composer send, or a card's "Run task"); false =
// just create the task and open its detail page in the pre-run state.
function assign(taskPrompt: string, title?: string, module?: CoworkModule, run = true) {
  const p = taskPrompt.trim()
  if (!p) return
  // A predefined card (module given) scopes to its own module; a free-form
  // composer prompt uses the sources the user toggled on.
  const fromCatalog = !!module
  const active = sources.value.filter((s) => isSourceOn(s.id)).map((s) => s.name) as CoworkModule[]
  const primary = module ?? inferModule(p)
  const modules = fromCatalog ? [primary] : (active.length ? active : [primary])
  const task = addTask({
    title: title ?? (p.length > 52 ? p.slice(0, 50) + '…' : p),
    prompt: p,
    module: primary,
    modules,
    status: run ? 'running' : 'scheduled',
    createdAt: new Date().toISOString(),
    outputs: OUTPUTS.filter((o) => isOutputOn(o.id)).map((o) => o.name),
    sources: modules,
    model: model.value,
  })
  prompt.value = ''
  // Running (when requested) happens on the task detail page, which owns the run
  // history + result; otherwise the detail opens in its pre-run state.
  router.push({ path: `/cowork-tasks/${task.id}`, query: run ? { run: '1' } : {} })
}

function inferModule(text: string): CoworkModule {
  const t = text.toLowerCase()
  if (/(payroll|attendance|employee|contract|resign|leave|hr\b)/.test(t)) return 'HR'
  if (/(stock|warehouse|sku|inbound|outbound|fulfil|pick|pack|cycle count)/.test(t)) return 'WMS'
  if (/(invoice|receivable|payable|bill|reconcil|cash|payment|close)/.test(t)) return 'Finance'
  if (/(work order|production|bom|manufactur)/.test(t)) return 'Production'
  if (/(order|deliver|ship)/.test(t)) return 'Sales'
  return 'CRM'
}

function startRun(task: CoworkTask) {
  openTaskId.value = task.id
  plan.value = null
  planSource.value = ''
  apiDone.value = false
  runState.value = 'working'
  liveSteps.value = DEFAULT_STEPS
  activeStepIndex.value = 0
  if (stepTimer) clearInterval(stepTimer)
  stepTimer = setInterval(() => {
    if (activeStepIndex.value < liveSteps.value.length) activeStepIndex.value += 1
    maybeComplete()
  }, 1400)
  fetchPlan(task)
}

async function fetchPlan(task: CoworkTask) {
  try {
    const activeSources = sources.value.filter((s) => isSourceOn(s.id)).map((s) => s.name)
    const activeOutputs = OUTPUTS.filter((o) => isOutputOn(o.id)).map((o) => o.name)
    const res = await $fetch<{ plan: Plan; source: 'gemini' | 'fallback' }>('/api/cowork/plan', {
      method: 'POST',
      body: { task: task.prompt, context: build(), model: model.value, sources: activeSources, outputs: activeOutputs },
    })
    plan.value = res.plan
    planSource.value = res.source
    if (res.plan?.steps?.length) liveSteps.value = res.plan.steps
  } catch {
    planSource.value = 'fallback'
  } finally {
    apiDone.value = true
    maybeComplete()
  }
}

function maybeComplete() {
  if (apiDone.value && plan.value && activeStepIndex.value >= liveSteps.value.length) {
    if (stepTimer) { clearInterval(stepTimer); stepTimer = null }
    setTimeout(finishRun, 600)
  }
}
function finishRun() {
  if (!openTask.value || !plan.value) return
  runState.value = 'completed'
  updateTask(openTask.value.id, {
    status: 'completed',
    completedAt: new Date().toISOString(),
    metric: plan.value.metric,
    planJson: JSON.stringify(plan.value),
  })
}

// ── Artifact downloads ───────────────────────────────────────────────────────
function downloadBlob(name: string, mime: string, content: string) {
  const url = URL.createObjectURL(new Blob([content], { type: mime }))
  const a = document.createElement('a')
  a.href = url; a.download = name; a.click()
  setTimeout(() => URL.revokeObjectURL(url), 1000)
}
function downloadCsv() {
  const s = plan.value?.artifacts?.spreadsheet
  if (!s) return
  const esc = (v: string) => `"${String(v ?? '').replace(/"/g, '""')}"`
  const csv = [s.columns, ...s.rows].map((r) => r.map(esc).join(',')).join('\n')
  downloadBlob(`${(s.title || 'cowork').replace(/\s+/g, '-').toLowerCase()}.csv`, 'text/csv', csv)
}
async function downloadPdf() {
  const p = plan.value?.artifacts?.pdf
  if (!p) return
  const { default: JsPDF } = await import('jspdf')
  const doc = new JsPDF({ unit: 'pt', format: 'a4' })
  const M = 48; let y = M
  doc.setFontSize(18); doc.text(p.title || 'Report', M, y); y += 28
  doc.setFontSize(11)
  for (const sec of p.sections) {
    doc.setFont('helvetica', 'bold'); doc.text(sec.heading, M, y); y += 18
    doc.setFont('helvetica', 'normal')
    for (const line of doc.splitTextToSize(sec.body, 500)) {
      if (y > 780) { doc.addPage(); y = M }
      doc.text(line, M, y); y += 15
    }
    y += 12
  }
  doc.save(`${(p.title || 'cowork').replace(/\s+/g, '-').toLowerCase()}.pdf`)
}
