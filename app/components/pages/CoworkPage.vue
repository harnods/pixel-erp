  if (typeof q.task === 'string' && q.task.trim() && q.run === '1') {
    assign(q.task)
    // Strip task/run from the URL; the workspace stays open via openTask.
    router.replace({ path: '/cowork', query: {} })
  }
  handleQueryTriggers()
})
onBeforeUnmount(() => { if (stepTimer) clearInterval(stepTimer) })
