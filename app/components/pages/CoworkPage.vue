  return [...list].sort((a, b) => {
    if (!!b.pinned !== !!a.pinned) return a.pinned ? -1 : 1
    const at = a.lastUsedAt ?? '', bt = b.lastUsedAt ?? ''
    if (at !== bt) return bt.localeCompare(at)
