const connecting = ref('')                          // id currently authorising
const connError = reactive<Record<string, string>>({})   // inline error per card
const connSample = reactive<Record<string, string>>({})  // live proof per card (e.g. email)

async function connectGoogle(c: CoworkConnection) {
  connError[c.id] = ''
  if (!google.isConfigured.value) {
    connError[c.id] = 'Google client ID not configured yet (NUXT_PUBLIC_GOOGLE_CLIENT_ID).'
    return
  }
  connecting.value = c.id
  try {
    const { sample } = await google.connect(c.scope!)
    setConnection(c.id, true)
    if (sample) connSample[c.id] = sample
    toast.notify({ variant: 'success', title: `${c.name} connected` })
  } catch (e: any) {
    connError[c.id] = e?.message === 'Google client ID not configured'
      ? 'Google client ID not configured yet.'
      : 'Could not connect. Please try again.'
  } finally {
    connecting.value = ''
  }
}
function disconnectConnection(c: CoworkConnection) {
  if (c.provider === 'google' && c.scope) google.disconnect(c.scope)
  delete connSample[c.id]
  // A custom MCP server is uninstalled (removed) rather than just disconnected.
  if (c.id.startsWith('custom-')) {
    removeCoworkConnection(c.id)
    toast.notify({ variant: 'success', title: `${c.name} uninstalled` })
    return
  }
  setConnection(c.id, false)
  toast.notify({ variant: 'success', title: `${c.name} disconnected` })
}
