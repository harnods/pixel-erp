const CONN_MIN_CARD = 300   // ~3 cols on a normal stage, scaling up to 6 when very wide
const CONN_MAX_COLS = 6
const connGridEl = ref<HTMLElement | null>(null)
const connCols = ref(3)
function recomputeConnCols() {
  const w = connGridEl.value?.clientWidth ?? 0
  if (!w) return
  connCols.value = Math.max(1, Math.min(CONN_MAX_COLS, Math.floor(w / CONN_MIN_CARD)))
}
let connRo: ResizeObserver | null = null
watch([section, connGridEl], async () => {
  if (section.value !== 'Connections') { connRo?.disconnect(); connRo = null; return }
  await nextTick()
  recomputeConnCols()
  if (connGridEl.value && 'ResizeObserver' in window && !connRo) {
    connRo = new ResizeObserver(recomputeConnCols)
    connRo.observe(connGridEl.value)
  }
}, { immediate: true })
onBeforeUnmount(() => connRo?.disconnect())

function connLogo(name: string): string {
  return name.replace(/[^A-Za-z0-9 ]/g, '').split(/\s+/).filter(Boolean).slice(0, 2).map((w) => w[0]!.toUpperCase()).join('').slice(0, 2)
}

interface ConnSection { category: CoworkConnectionCategory; items: CoworkConnection[]; filler: number }
const connSections = computed<ConnSection[]>(() => {
  const q = connSearch.value.trim().toLowerCase()
  const out: ConnSection[] = []
  for (const cat of COWORK_CONNECTION_CATEGORIES) {
    const items = coworkConnections.filter((c) =>
      c.categories.includes(cat)
      && (connStatus.value === 'all' || (connStatus.value === 'connected' ? c.connected : !c.connected))
      && (!q || c.name.toLowerCase().includes(q) || (c.detail ?? '').toLowerCase().includes(q)))
    if (!items.length) continue
    const rem = items.length % connCols.value
    out.push({ category: cat, items, filler: rem === 0 ? 0 : connCols.value - rem })
  }
  return out
})
function toggleConnection(c: CoworkConnection) {
  if (c.connected) { disconnectConnection(c); return }
  if (c.provider === 'google') connectGoogle(c)
  else connectFake(c)
}
function manageConnection(c: CoworkConnection) {
