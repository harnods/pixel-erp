function fmtTime(hhmm: string): string {
  const [h, m] = hhmm.split(':').map(Number)
  const ap = h! < 12 ? 'am' : 'pm'
  const h12 = h! % 12 || 12
  return m ? `${h12}:${String(m).padStart(2, '0')}${ap}` : `${h12}${ap}`
}
